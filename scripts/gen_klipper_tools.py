"""Generate the per-tool Klipper files in klipper/nexus/tools and
klipper/nexus/filament from the board pinouts.

Pins: docs/pinout-toolboard.md and docs/pinout-dockboard.md.
Run after a pinout change:  python3 scripts/gen_klipper_tools.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / "klipper" / "nexus"

# tool: (heater, thermistor, runout, motion, dock fan, spare pin for the
# disabled placeholder heater)
PINS = {
    0: ("PB13", "PA0", "PC12", "PC11", "PB13", "PC0"),
    1: ("PB14", "PA1", "PC10", "PB9", "PB14", "PC1"),
    2: ("PB15", "PA2", "PB8", "PB5", "PB15", "PC2"),
    3: ("PA8", "PA3", "PD6", "PD5", "PA8", "PC3"),
    4: ("PC6", "PA4", "PD4", "PD3", "PC6", "PC5"),
    5: ("PC7", "PA5", "PD2", "PD1", "PC7", "PB2"),
    6: ("PD8", "PA6", "PD0", "PC9", "PD8", "PB10"),
    7: ("PD9", "PA7", "PC8", "PA15", "PD9", "PB11"),
}

HEADER = "# SPDX-License-Identifier: GPL-3.0-or-later\n# Generated by scripts/gen_klipper_tools.py. Do not edit.\n"

TOOL_VARS = """[gcode_macro _NEXUS_T{t}]
variable_enabled: {enabled}
variable_dock_x: 0.0
variable_dock_y: 0.0
variable_offset_x: 0.0
variable_offset_y: 0.0
variable_offset_z: 0.0
gcode:
"""


def ext(t):
    return "extruder" if t == 0 else f"extruder{t}"


def tool(t, p):
    heater, therm, _, _, fan, _ = p
    return (HEADER
            + f"# Nexus tool T{t}: pins and defaults. Override settings in nexus.cfg.\n\n"
            + TOOL_VARS.format(t=t, enabled="True")
            + f"""
[{ext(t)}]
heater_pin: nexus_tools:{heater}
sensor_pin: nexus_tools:{therm}
sensor_type: Generic 3950
# 4700 = PT1000 jumper open (NTC), 2195 = jumper closed (PT1000)
pullup_resistor: 4700
nozzle_diameter: 0.400
filament_diameter: 1.750
# The YUDX latch moves E together with X/Y; allow that.
max_extrude_cross_section: 5.0
max_extrude_only_distance: 101.0
min_temp: 0
max_temp: 300
min_extrude_temp: 170

[heater_fan nexus_dock_fan_t{t}]
pin: nexus_docks:{fan}
heater: {ext(t)}
heater_temp: 50.0

[gcode_macro T{t}]
description: Select tool {t}
gcode:
  NEXUS_CHANGE_TOOL TOOL={t}
""")


def disabled(t, p):
    spare = p[5]
    return (HEADER
            + f"""# Nexus tool T{t}: DISABLED placeholder.
# Klipper loads extruder, extruder1, ... up to the first missing number, so a
# disabled tool in the middle needs a placeholder to keep the higher tools.
# The heater drives an unused MCU pin and the "thermistor" is the MCU
# temperature. The macros refuse to heat or select this tool.

"""
            + TOOL_VARS.format(t=t, enabled="False")
            + f"""
[{ext(t)}]
heater_pin: nexus_tools:{spare}
sensor_type: temperature_combined
sensor_list: temperature_sensor nexus_tools_mcu
combination_method: max
maximum_deviation: 500
min_temp: -40
max_temp: 150
min_extrude_temp: 150
nozzle_diameter: 0.400
filament_diameter: 1.750
control: watermark

[gcode_macro T{t}]
description: Tool {t} is disabled
gcode:
  {{action_raise_error("Nexus: T{t} is disabled in nexus.cfg")}}
""")


def runout(t, p):
    return (HEADER
            + f"""# Nexus tool T{t}: runout switch on filament connector pin 1.
# Default: D2F with COM to GND (pin 2) and NO to pin 1, low = filament.
# For a sensor with the opposite logic, override switch_pin in nexus.cfg
# without the '!': switch_pin: nexus_tools:{p[2]}

[filament_switch_sensor nexus_t{t}_runout]
switch_pin: !nexus_tools:{p[2]}
pause_on_runout: False
runout_gcode: _NEXUS_RUNOUT TOOL={t} SENSOR=runout
insert_gcode: _NEXUS_INSERT TOOL={t}
""")


def motion(t, p):
    return (HEADER
            + f"""# Nexus tool T{t}: filament motion (clog) sensor on filament connector pin 4.
# Bound to the shared extruder drive; only enabled while T{t} is mounted.

[filament_motion_sensor nexus_t{t}_motion]
switch_pin: nexus_tools:{p[3]}
detection_length: 10.0
extruder: extruder_stepper nexus_extruder
pause_on_runout: False
runout_gcode: _NEXUS_RUNOUT TOOL={t} SENSOR=motion
""")


def main():
    for t, p in PINS.items():
        (ROOT / "tools" / f"t{t}.cfg").write_text(tool(t, p))
        (ROOT / "tools" / f"t{t}_disabled.cfg").write_text(disabled(t, p))
        (ROOT / "filament" / f"t{t}_runout.cfg").write_text(runout(t, p))
        (ROOT / "filament" / f"t{t}_motion.cfg").write_text(motion(t, p))


if __name__ == "__main__":
    main()
